import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const outputPath = resolve("public/monster-master-pixi-bundle.js");
const check = process.argv.includes("--check");

const result = await build({
  entryPoints: ["src/browser/monster-master-pixi-entry.js"],
  bundle: true,
  write: false,
  format: "esm",
  platform: "browser",
  target: ["es2022"],
  minify: true,
  legalComments: "eof",
  sourcemap: false,
  logLevel: "warning",
  banner: {
    js: "/* Generated by scripts/build-monster-master-pixi.mjs; PixiJS 8.19.0 (MIT). */",
  },
});

if (result.outputFiles.length !== 1) {
  throw new Error(`Expected one Monster Master Pixi bundle, received ${result.outputFiles.length}.`);
}

const output = result.outputFiles[0].text;
if (check) {
  const committed = await readFile(outputPath, "utf8").catch(() => "");
  if (committed !== output) {
    throw new Error("The committed Monster Master Pixi bundle is stale. Run npm run build:monster-master-pixi.");
  }
  console.log("Monster Master Pixi bundle is reproducible and current.");
} else {
  await writeFile(outputPath, output, "utf8");
  console.log(`Wrote ${outputPath} (${Buffer.byteLength(output)} bytes).`);
}
